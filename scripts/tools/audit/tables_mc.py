def rows(text):
    out = []
    for line in text.splitlines():
        t, rest = line.split(':'); t = int(t); v0, v5 = rest.split()
        out.append((float(t), float(v0)))
        if v5 != '?':
            v5 = float(v5); half = t - 0.5 if t < 0 or (t == 0 and v5 > float(v0)) else t + 0.5
            out.append((half, v5))
    return out

